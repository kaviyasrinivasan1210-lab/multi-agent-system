"""
Reports & Repository View — Document Archive, Executive Export Center & Agent Audit Trail.
Styled with high-contrast Dark Neon Cyber aesthetic.
"""

import streamlit as st
import pandas as pd
from data.mock_data import get_repository_documents, get_agent_audit_logs


def render_reports_repo_view() -> None:
    """Renders the Reports Repository and Audit Log view."""
    st.markdown(
        """
        <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 1.25rem;">
            <div>
                <h2 style="font-size: 1.4rem; font-weight: 800; color: #F8FAFC; margin: 0 0 4px 0; text-shadow: 0 0 12px rgba(0, 240, 255, 0.4);">
                    📄 Reports Repository & Decision Audit Trail
                </h2>
                <p style="font-size: 0.85rem; color: #94A3B8; margin: 0;">
                    Export verified executive briefings, download historical data, and audit autonomous agent actions.
                </p>
            </div>
            <div>
                <span class="badge-pill badge-cyan" style="font-size: 0.75rem;">
                    ● Enterprise Compliance Ready
                </span>
            </div>
        </div>
        """,
        unsafe_allow_html=True,
    )

    # 1. Executive Report Generator Card
    st.markdown(
        """
        <div class="saas-card">
            <div class="saas-card-header">
                <div>
                    <h3 class="saas-card-title">⚡ Autonomous Executive Report Generator</h3>
                    <p class="saas-card-subtitle">Synthesize multi-agent data streams into an official executive briefing document.</p>
                </div>
            </div>
        """,
        unsafe_allow_html=True,
    )

    r_col1, r_col2, r_col3 = st.columns([2, 1, 1])

    with r_col1:
        report_template = st.selectbox(
            "Report Template Type",
            [
                "Q3 Executive Business Review (EBR) — Full Multi-Agent Synthesis",
                "Monthly Revenue & Sales Pipeline Diagnostic",
                "Customer Health & Churn Risk Action Plan",
                "Marketing Attribution & ROAS Channel Performance",
                "Competitor Intelligence & SWOT Benchmark Dossier",
            ],
        )

    with r_col2:
        export_format = st.selectbox("Export Format", ["PDF Document (.pdf)", "CSV Data Package (.csv)", "Markdown Briefing (.md)"])

    with r_col3:
        st.markdown("<div style='margin-top: 25px;'></div>", unsafe_allow_html=True)
        generate_clicked = st.button("🚀 Compile Report", type="primary", use_container_width=True)

    if generate_clicked:
        with st.spinner("Compiling cross-agent data streams and generating document..."):
            st.success(f"Report compiled successfully! '{report_template.split('—')[0]}' is ready.")

            sample_csv = pd.DataFrame({
                "Metric": ["ARR", "Pipeline", "Blended CAC", "CSAT", "NRR"],
                "Value": ["$1,248,500", "$2,840,000", "$482", "94.2%", "114.2%"],
                "Status": ["Target Exceeded", "Healthy", "Efficient", "High", "Expansion"],
            }).to_csv(index=False).encode("utf-8")

            d1, d2 = st.columns([1, 3])
            with d1:
                st.download_button(
                    label="⬇️ Download Document",
                    data=sample_csv,
                    file_name="Executive_Business_Review_Q3_2026.csv",
                    mime="text/csv",
                    use_container_width=True,
                )

    st.markdown("</div>", unsafe_allow_html=True)

    # 2. Document Repository Archive Table
    st.markdown(
        """
        <div class="saas-card">
            <div class="saas-card-header">
                <div>
                    <h3 class="saas-card-title">📚 Document & Dataset Repository</h3>
                    <p class="saas-card-subtitle">Historical briefings, data exports, and verified executive memorandums.</p>
                </div>
            </div>
        """,
        unsafe_allow_html=True,
    )

    docs_df = get_repository_documents()

    st.dataframe(
        docs_df,
        column_config={
            "Document Name": st.column_config.TextColumn("File Name", width="large"),
            "Generated By": st.column_config.TextColumn("Authoring Agent", width="medium"),
            "Generated Date": st.column_config.TextColumn("Date"),
            "File Size": st.column_config.TextColumn("Size"),
            "Status": st.column_config.TextColumn("Status"),
        },
        use_container_width=True,
        hide_index=True,
    )
    st.markdown("</div>", unsafe_allow_html=True)

    # 3. Transparent Multi-Agent Decision Audit Trail
    st.markdown(
        """
        <div class="saas-card">
            <div class="saas-card-header">
                <div>
                    <h3 class="saas-card-title">🛡️ Autonomous Agent Decision Audit Trail</h3>
                    <p class="saas-card-subtitle">Verifiable log of every high-impact agent inference, confidence score, and business action.</p>
                </div>
                <span class="badge-pill badge-success">Cryptographic State Hash</span>
            </div>
        """,
        unsafe_allow_html=True,
    )

    audit_df = get_agent_audit_logs()

    st.dataframe(
        audit_df,
        column_config={
            "Timestamp": st.column_config.TextColumn("Timestamp (UTC)", width="medium"),
            "Agent": st.column_config.TextColumn("Executing Agent", width="medium"),
            "Action Executed": st.column_config.TextColumn("Action & Query Summary", width="large"),
            "Confidence": st.column_config.TextColumn("Model Confidence"),
            "Impact Level": st.column_config.TextColumn("Business Scope"),
        },
        use_container_width=True,
        hide_index=True,
    )
    st.markdown("</div>", unsafe_allow_html=True)
